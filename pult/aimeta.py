"""Pult: stopy AI v metadatech (C2PA / Content Credentials, IPTC „trainedAlgorithmicMedia“, podpisy generátorů).

Instagram, YouTube a TikTok podle nich videa a obrázky označují jako „vytvořeno pomocí AI“. Prohledává se
jen metadatová část souboru (u MP4/MOV vše kromě boxu mdat, u JPEG segmenty před obrazovými daty,
u PNG chunky kromě IDAT), takže náhodná shoda v komprimovaných datech nevznikne.
"""
import json
import os
import re
import struct
import subprocess

import config

# (regulární výraz nad bajty, co to je)
MARKERS = [
    (rb"c2pa", "C2PA (Content Credentials)"),
    (rb"contentauth|cai\.manifest|jumdc2pa", "C2PA (Content Credentials)"),
    (rb"compositeWithTrainedAlgorithmicMedia", "IPTC: složeno s AI"),
    (rb"trainedAlgorithmicMedia", "IPTC: vytvořeno AI"),
    (rb"algorithmicMedia", "IPTC: algoritmicky vytvořeno"),
    (rb"\bAIGC\b|AIGCLabel|\"Label\":\s*\"?1", "AIGC štítek (TikTok, Kling, Douyin)"),
    (rb"OpenAI|ChatGPT|DALL[\-\xb7 ]?E|\bSora\b", "OpenAI (ChatGPT, DALL·E, Sora)"),
    (rb"Midjourney", "Midjourney"),
    (rb"Adobe Firefly|Firefly", "Adobe Firefly"),
    (rb"Stable Diffusion|stability\.ai|ComfyUI|Automatic1111", "Stable Diffusion"),
    (rb"Google (Imagen|Veo|Gemini)|SynthID|\bImagen\b|\bVeo ?[23]\b|Gemini", "Google (Imagen, Veo, Gemini)"),
    (rb"Runway(ML)?\b|Gen-[234]\b", "Runway"),
    (rb"Kling(AI)?\b|Kuaishou", "Kling"),
    (rb"Higgsfield", "Higgsfield"),
    (rb"Anthropic|Claude", "Claude (Anthropic)"),
    (rb"Made with AI|AI[ -]generated|Generated by AI|Generated with AI", "Označeno jako AI"),
]
_rx = [(re.compile(p, re.I), what) for p, what in MARKERS]
LIMIT = 24 * 1024 * 1024  # max. bajtů metadat, které čteme


def _mp4_meta(f, size):
    """Bajty všech boxů nejvyšší úrovně kromě mdat (moov, uuid, meta, udta…)."""
    out, pos = bytearray(), 0
    while pos + 8 <= size and len(out) < LIMIT:
        f.seek(pos)
        h = f.read(16)
        if len(h) < 8:
            break
        n, typ = struct.unpack(">I4s", h[:8])
        hdr = 8
        if n == 1 and len(h) >= 16:
            n, hdr = struct.unpack(">Q", h[8:16])[0], 16
        elif n == 0:
            n = size - pos
        if n < hdr:
            break
        if typ not in (b"mdat", b"free", b"skip", b"wide"):
            f.seek(pos)
            out += f.read(min(n, LIMIT - len(out)))
        pos += n
    return bytes(out)


def _jpeg_meta(f):
    out = bytearray()
    if f.read(2) != b"\xff\xd8":
        return b""
    while len(out) < LIMIT:
        m = f.read(2)
        if len(m) < 2 or m[0] != 0xFF:
            break
        if m[1] in (0xD9, 0xDA):  # konec / začátek obrazových dat
            break
        ln = f.read(2)
        if len(ln) < 2:
            break
        n = struct.unpack(">H", ln)[0]
        out += f.read(max(0, n - 2))
    return bytes(out)


def _png_meta(f):
    out = bytearray()
    if f.read(8) != b"\x89PNG\r\n\x1a\n":
        return b""
    while len(out) < LIMIT:
        h = f.read(8)
        if len(h) < 8:
            break
        n, typ = struct.unpack(">I4s", h)
        if typ == b"IDAT":
            f.seek(n + 4, 1)
            continue
        out += typ + f.read(n)
        f.seek(4, 1)
        if typ == b"IEND":
            break
    return bytes(out)


def _generic(f, size):
    """Ostatní formáty (webp, heic, webm…): začátek a konec souboru."""
    f.seek(0)
    head = f.read(min(size, 2 * 1024 * 1024))
    tail = b""
    if size > 4 * 1024 * 1024:
        f.seek(size - 2 * 1024 * 1024)
        tail = f.read()
    return head + tail


def _tags(path):
    """Textové tagy přes ffprobe (comment, encoder, software…)."""
    ff = config.tool("ffprobe")
    if not ff:
        return b""
    try:
        r = subprocess.run([ff, "-v", "error", "-show_entries", "format_tags:stream_tags", "-of", "json", path],
                           capture_output=True, timeout=20)
        return r.stdout or b""
    except Exception:
        return b""


def scan(path):
    """Vrací seznam nálezů [{what, hint}] (prázdný = nic podezřelého)."""
    try:
        size = os.path.getsize(path)
        with open(path, "rb") as f:
            head = f.read(16)
            f.seek(0)
            ext = os.path.splitext(path)[1].lower()
            if head[4:8] == b"ftyp" or ext in (".mp4", ".mov", ".m4v", ".heic", ".heif", ".avif", ".3gp"):
                data = _mp4_meta(f, size)
            elif head[:2] == b"\xff\xd8":
                data = _jpeg_meta(f)
            elif head[:8] == b"\x89PNG\r\n\x1a\n":
                data = _png_meta(f)
            else:
                data = _generic(f, size)
    except OSError:
        return []
    data += _tags(path)
    found, seen = [], set()
    for rx, what in _rx:
        m = rx.search(data)
        if m and what not in seen:
            seen.add(what)
            s = max(0, m.start() - 24)
            ctx = re.sub(rb"[^\x20-\x7e]+", b" ", data[s:m.end() + 40]).decode("ascii", "replace").strip()
            found.append({"what": what, "hint": ctx[:90]})
    names = {f["what"] for f in found}
    if names & {"IPTC: vytvořeno AI", "IPTC: složeno s AI"}:
        found = [f for f in found if f["what"] != "IPTC: algoritmicky vytvořeno"]
    return found


def clean_copy(path):
    """Kopie bez metadat vedle originálu (originál zůstane beze změny). Vrací cestu ke kopii."""
    ff = config.tool("ffmpeg")
    if not ff:
        raise RuntimeError("Chybí ffmpeg.")
    base, ext = os.path.splitext(path)
    out = base + " (bez metadat)" + ext
    i = 2
    while os.path.exists(out):
        out = base + " (bez metadat %d)" % i + ext
        i += 1
    video = ext.lower() in (".mp4", ".mov", ".m4v", ".webm", ".mkv")
    cmd = [ff, "-v", "error", "-y", "-i", path, "-map", "0", "-map_metadata", "-1", "-map_chapters", "-1"]
    if video:
        cmd += ["-c", "copy", "-fflags", "+bitexact", "-flags:v", "+bitexact", "-flags:a", "+bitexact"]
        if ext.lower() in (".mp4", ".mov", ".m4v"):
            cmd += ["-movflags", "+faststart"]
    else:
        cmd += ["-q:v", "1"] if ext.lower() in (".jpg", ".jpeg") else []
    cmd.append(out)
    r = subprocess.run(cmd, capture_output=True, timeout=600)
    if r.returncode != 0 or not os.path.isfile(out):
        raise RuntimeError((r.stderr or b"").decode("utf-8", "replace")[-300:] or "ffmpeg selhal")
    left = scan(out)
    return out, left


if __name__ == "__main__":
    import sys
    for p in sys.argv[1:]:
        print(p, json.dumps(scan(p), ensure_ascii=False))
